"""Command-line entry point: `python -m app.cli --help`."""
import argparse
import time


def _style(parser):
    parser.add_argument("--style", default="football", help="corpus/<style>.txt to use (default: football)")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(prog="stylistic-text-generator-comparator", description="Sports journalists use this to compare text generated by a LoRA-adapted LLM with an N-gram model, both fine-tuned on specific sports commentary styles.")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("hello", help="check that everything is wired up")

    p = sub.add_parser("corpus", help="milestone 1: show the styles and the size of each corpus")

    p = sub.add_parser("ngram", help="milestone 2: generate text with the n-gram model")
    _style(p)
    p.add_argument("--prompt", default="")
    p.add_argument("--n", type=int, default=3)
    p.add_argument("--samples", type=int, default=3)
    p.add_argument("--seed", type=int, default=0)

    p = sub.add_parser("train", help="milestones 3-4: inject LoRA into distilgpt2 and fine-tune it on a style")
    _style(p)
    p.add_argument("--epochs", type=int, default=4)
    p.add_argument("--lr", type=float, default=2e-3)
    p.add_argument("--rank", type=int, default=8)
    p.add_argument("--alpha", type=float, default=16.0)

    p = sub.add_parser("generate", help="milestone 5: generate text with the trained LoRA model")
    _style(p)
    p.add_argument("--prompt", required=True)
    p.add_argument("--samples", type=int, default=3)
    p.add_argument("--seed", type=int, default=0)

    p = sub.add_parser("compare", help="milestone 6: n-gram vs LoRA (vs the untouched base model) on one prompt")
    _style(p)
    p.add_argument("--prompt", required=True)
    p.add_argument("--n", type=int, default=3)
    p.add_argument("--samples", type=int, default=2)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--with-base", action="store_true", help="also show distilgpt2 with the adapter switched off")
    p.add_argument("--rate", action="store_true", help="ask which model sounded more like the style and save it")

    p = sub.add_parser("ratings", help="show the ratings saved by `compare --rate`")

    p = sub.add_parser("evaluate", help="score every model on held-out passages and write results/<style>.md")
    _style(p)
    p.add_argument("--epochs", type=int, default=4)
    p.add_argument("--seed", type=int, default=0)

    args = parser.parse_args(argv)
    if args.command == "hello":
        print("Stylistic Text Generator Comparator is ready. Try: python -m app.cli corpus")
        return

    from app import core

    if args.command == "corpus":
        for style in core.available_styles():
            print(style, core.corpus_stats(core.load_corpus(style)))

    elif args.command == "ngram":
        model = core.NGramModel(args.n).fit(core.load_corpus(args.style))
        for i in range(args.samples):
            print(f"{i + 1}. {model.generate(args.prompt, seed=args.seed + i)}")

    elif args.command == "evaluate":
        _evaluate(core, args)

    elif args.command == "train":
        passages = core.load_corpus(args.style)
        model, tok = core.load_base_model()
        layers = core.inject_lora(model, ("c_attn",), r=args.rank, alpha=args.alpha)
        trainable, total = core.count_parameters(model)
        print(f"LoRA on {layers} layers: training {trainable:,} of {total:,} parameters "
              f"({100 * trainable / total:.2f}%)")
        before = core.evaluate_loss(model, tok, passages)
        start = time.time()
        core.train_lora(model, tok, passages, epochs=args.epochs, lr=args.lr, log=print)
        after = core.evaluate_loss(model, tok, passages)
        print(f"loss on the corpus: {before:.3f} before -> {after:.3f} after ({time.time() - start:.0f}s)")
        path = core.adapter_path(args.style)
        core.save_lora(model, path, {"base_model": core.BASE_MODEL, "targets": ["c_attn"],
                                     "r": args.rank, "alpha": args.alpha, "style": args.style})
        print(f"saved adapter to {path}")

    elif args.command == "generate":
        model, tok = _lora(core, args.style)
        for i in range(args.samples):
            print(f"{i + 1}. {core.generate_llm(model, tok, args.prompt, seed=args.seed + i)}")

    elif args.command == "compare":
        passages = core.load_corpus(args.style)
        ngram = core.NGramModel(args.n).fit(passages)
        model, tok = _lora(core, args.style)

        def lora(prompt, seed):
            core.set_lora_enabled(model, True)
            return core.generate_llm(model, tok, prompt, seed=seed)

        def base(prompt, seed):
            core.set_lora_enabled(model, False)
            return core.generate_llm(model, tok, prompt, seed=seed)

        generators = {f"{args.n}-gram": lambda p, s: ngram.generate(p, seed=s), "LoRA distilgpt2": lora}
        if args.with_base:
            generators["base distilgpt2 (no LoRA)"] = base
        result = core.compare(args.prompt, generators, passages, samples=args.samples, seed=args.seed)
        print(core.render_comparison(result))
        if args.rate:
            labels = list(generators)
            for i, label in enumerate(labels, 1):
                print(f"  {i}) {label}")
            choice = input("Which sounded most like real commentary? number (Enter to skip): ").strip()
            if choice.isdigit() and 1 <= int(choice) <= len(labels):
                from app.storage import Store
                store = Store()
                ratings = store.get("ratings", [])
                ratings.append({"style": args.style, "prompt": args.prompt, "winner": labels[int(choice) - 1],
                                "comparison": result})
                store.put("ratings", ratings)
                print(f"saved. {len(ratings)} rating(s) so far; see them with `python -m app.cli ratings`")

    elif args.command == "ratings":
        from collections import Counter
        from app.storage import Store
        ratings = Store().get("ratings", [])
        if not ratings:
            print("No ratings yet. Run `compare --rate`.")
        for (style, winner), n in sorted(Counter((r["style"], r["winner"]) for r in ratings).items()):
            print(f"{style:10} {winner:30} {n}")


def _evaluate(core, args):
    """Train every model on 5/6 of the corpus, then score them on the 1/6 they never saw."""
    from pathlib import Path

    train, test = core.split_corpus(core.load_corpus(args.style))
    print(f"{args.style}: {len(train)} training passages, {len(test)} held-out passages")
    unigram = core.NGramModel(1).fit(train)
    trigram = core.NGramModel(3).fit(train)
    model, tok = core.load_base_model()
    import torch
    torch.manual_seed(args.seed)                               # same LoRA starting weights on every run
    core.inject_lora(model, ("c_attn",), r=8, alpha=16)       # B = 0, so this is still exactly the base model

    ppl = {"unigram (simple baseline)": core.perplexity_per_word(unigram.passage_nll, test),
           "3-gram": core.perplexity_per_word(trigram.passage_nll, test),
           "base distilgpt2 (no LoRA)": core.perplexity_per_word(lambda p: core.llm_passage_nll(model, tok, p), test)}
    base_state = {k: v.clone() for k, v in model.state_dict().items() if "lora_" in k}
    core.train_lora(model, tok, train, epochs=args.epochs, seed=args.seed, log=print)
    ppl["LoRA distilgpt2"] = core.perplexity_per_word(lambda p: core.llm_passage_nll(model, tok, p), test)
    trained_state = {k: v.clone() for k, v in model.state_dict().items() if "lora_" in k}

    def llm(state):
        def fn(prompt, seed):
            model.load_state_dict(state, strict=False)
            return core.generate_llm(model, tok, prompt, seed=seed)
        return fn

    gens = {"unigram (simple baseline)": lambda p, s: unigram.generate(p, seed=s),
            "3-gram": lambda p, s: trigram.generate(p, seed=s),
            "base distilgpt2 (no LoRA)": llm(base_state),
            "LoRA distilgpt2": llm(trained_state)}
    prompts = [" ".join(t.split()[:4]) for t in test]           # openings of passages no model trained on
    runs = [core.compare(p, gens, train, samples=2, seed=args.seed) for p in prompts]
    stats = {label: {k: round(sum(core.summarise(r)[label][k] for r in runs) / len(runs), 2)
                     for k in ("words", "distinct_2", "copied_4")} for label in gens}

    lines = [f"## {args.style}", "",
             f"Trained on {len(train)} passages, scored on {len(test)} held-out passages. Generation numbers average "
             f"2 samples for each of {len(prompts)} held-out openings.", "",
             "| Model | Held-out perplexity per word (lower is better) | copied_4 (lower = less copying) "
             "| distinct_2 | words |", "|---|---|---|---|---|"]
    for label in gens:
        s = stats[label]
        lines.append(f"| {label} | {ppl[label]:.1f} | {s['copied_4']:.2f} | {s['distinct_2']:.2f} | {s['words']:.0f} |")
    lines += ["", f"Example, prompt \"{prompts[0]}\":", ""]
    lines += [f"- **{label}:** {runs[0]['results'][label][0]['text']}" for label in gens]
    report = "\n".join(lines) + "\n"
    print(report)
    out = Path("results") / f"{args.style}.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text(report, encoding="utf-8")
    print(f"written to {out}")


def _lora(core, style):
    path = core.adapter_path(style)
    if not path.exists():
        raise SystemExit(f"No adapter for {style!r} yet. Train one first: python -m app.cli train --style {style}")
    return core.load_lora_model(path)


if __name__ == "__main__":
    main()
